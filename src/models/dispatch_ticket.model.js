const { DataTypes: D } = require("sequelize");
const db = require("../config/postgres.config");
const { STATUS, TERMINAL } = require("../common/dispatch.constants");
const money = (field, nullable = false) => ({
  type: D.DECIMAL(12, 2),
  allowNull: nullable,
  ...(!nullable && { defaultValue: 0 }),
  field,
});
module.exports = db.define(
  "DispatchTicket",
  {
    id: { type: D.UUID, primaryKey: true, defaultValue: D.UUIDV4 },
    code: { type: D.STRING(20), unique: true, allowNull: false },
    journeyId: { type: D.UUID, allowNull: false, field: "journey_id" },
    userId: { type: D.UUID, allowNull: false, field: "user_id" },
    vehicleProfileId: {
      type: D.UUID,
      allowNull: false,
      field: "vehicle_profile_id",
    },
    providerId: { type: D.UUID, field: "provider_id" },
    targetProviderId: { type: D.UUID, field: "target_provider_id" },
    type: { type: D.ENUM("WALK_IN", "SOS", "TOW"), allowNull: false },
    status: {
      type: D.ENUM(...Object.values(STATUS)),
      allowNull: false,
      defaultValue: "1",
    },
    pickupLatitude: {
      type: D.DOUBLE,
      allowNull: false,
      field: "pickup_latitude",
    },
    pickupLongitude: {
      type: D.DOUBLE,
      allowNull: false,
      field: "pickup_longitude",
    },
    pickupAddress: { type: D.STRING(255), field: "pickup_address" },
    dropoffLatitude: { type: D.DOUBLE, field: "dropoff_latitude" },
    dropoffLongitude: { type: D.DOUBLE, field: "dropoff_longitude" },
    dropoffAddress: { type: D.STRING(255), field: "dropoff_address" },
    dropoffShopId: { type: D.UUID, field: "dropoff_shop_id" },
    description: D.STRING(2000),
    images: {
      type: D.ARRAY(D.STRING(2048)),
      defaultValue: [],
      allowNull: false,
    },
    vehicleSnapshot: {
      type: D.JSONB,
      allowNull: false,
      field: "vehicle_snapshot",
    },
    pricingSnapshot: {
      type: D.JSONB,
      allowNull: false,
      field: "pricing_snapshot",
    },
    requirements: { type: D.JSONB, allowNull: false },
    callOutFee: money("call_out_fee"),
    travelFee: money("travel_fee"),
    quoteAmount: money("quote_amount", true),
    waitingFee: money("waiting_fee"),
    totalAmount: money("total_amount"),
    quoteVoided: {
      type: D.BOOLEAN,
      defaultValue: false,
      allowNull: false,
      field: "quote_voided",
    },
    chargesVoided: {
      type: D.BOOLEAN,
      defaultValue: false,
      allowNull: false,
      field: "charges_voided",
    },
    assignmentDistanceMeters: {
      type: D.DOUBLE,
      field: "assignment_distance_meters",
    },
    arrivedAt: { type: D.DATE, field: "arrived_at" },
    waitingEndedAt: { type: D.DATE, field: "waiting_ended_at" },
    waitingMinutes: {
      type: D.INTEGER,
      defaultValue: 0,
      allowNull: false,
      field: "waiting_minutes",
    },
    acceptedAt: { type: D.DATE, field: "accepted_at" },
    resolvedAt: { type: D.DATE, field: "resolved_at" },
    cancelReason: { type: D.STRING(100), field: "cancel_reason" },
    unfixableReason: { type: D.STRING(50), field: "unfixable_reason" },
    unfixableImages: {
      type: D.ARRAY(D.STRING(2048)),
      defaultValue: [],
      allowNull: false,
      field: "unfixable_images",
    },
    formerAssignedUserIds: {
      type: D.ARRAY(D.UUID),
      defaultValue: [],
      allowNull: false,
      field: "former_assigned_user_ids",
    },
    formerAssignedShopIds: {
      type: D.ARRAY(D.UUID),
      defaultValue: [],
      allowNull: false,
      field: "former_assigned_shop_ids",
    },
    chatVersion: {
      type: D.INTEGER,
      defaultValue: 1,
      allowNull: false,
      field: "chat_version",
    },
    linkedTicketIds: {
      type: D.ARRAY(D.UUID),
      defaultValue: [],
      allowNull: false,
      field: "linked_ticket_ids",
    },
    handoverRequired: {
      type: D.BOOLEAN,
      allowNull: false,
      defaultValue: false,
      field: "handover_required",
    },
    parentTicketId: { type: D.UUID, field: "parent_ticket_id" },
    handoffKind: { type: D.STRING(20), field: "handoff_kind" },
    childTicketId: { type: D.UUID, field: "child_ticket_id" },
    towOffer: { type: D.JSONB, field: "tow_offer" },
    estimateAmount: money("estimate_amount", true),
    estimateExpiresAt: { type: D.DATE, field: "estimate_expires_at" },
    estimateStatus: { type: D.STRING(20), field: "estimate_status" },
    estimateVersion: {
      type: D.INTEGER,
      defaultValue: 0,
      allowNull: false,
      field: "estimate_version",
    },
    clientRequestId: { type: D.UUID, field: "client_request_id" },
    requestFingerprint: { type: D.STRING(64), field: "request_fingerprint" },
    queueExpiresAt: { type: D.DATE, field: "queue_expires_at" },
    arrivalDueAt: { type: D.DATE, field: "arrival_due_at" },
    lastProgressAt: { type: D.DATE, field: "last_progress_at" },
    lastProgressDistanceMeters: {
      type: D.DOUBLE,
      field: "last_progress_distance_meters",
    },
    noShowDetectedAt: { type: D.DATE, field: "no_show_detected_at" },
    safetyEscalatedAt: { type: D.DATE, field: "safety_escalated_at" },
    rematchCount: {
      type: D.INTEGER,
      defaultValue: 0,
      allowNull: false,
      field: "rematch_count",
    },
    intakeVersion: {
      type: D.INTEGER,
      defaultValue: 0,
      allowNull: false,
      field: "intake_version",
    },
    intakeReservationId: { type: D.UUID, field: "intake_reservation_id" },
    candidateIntakeReservationId: {
      type: D.UUID,
      field: "candidate_intake_reservation_id",
    },
    candidateShopId: { type: D.UUID, field: "candidate_shop_id" },
    disputeHold: {
      type: D.BOOLEAN,
      defaultValue: false,
      allowNull: false,
      field: "dispute_hold",
    },
    revision: { type: D.INTEGER, defaultValue: 1, allowNull: false },
  },
  {
    tableName: "dispatch_tickets",
    indexes: [
      { fields: ["user_id", "status"] },
      { fields: ["provider_id", "status"] },
      { fields: ["journey_id"] },
      {
        unique: true,
        fields: ["vehicle_profile_id"],
        where: { status: { [require("sequelize").Op.notIn]: TERMINAL } },
      },
      { unique: true, fields: ["user_id", "client_request_id"] },
      { unique: true, fields: ["parent_ticket_id", "handoff_kind"] },
    ],
  },
);
